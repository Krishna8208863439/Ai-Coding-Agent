export interface TemplateFile {
  path: string;
  content: string;
}

export function generateProjectFiles(
  name: string,
  template: string,
  prompt: string
): TemplateFile[] {
  const cleanName = name.toLowerCase().replace(/[^a-z0-9_-]/g, '-');

  switch (template) {
    case 'python':
      return [
        {
          path: 'app.py',
          content: `from flask import Flask, jsonify, request\nfrom flask_cors import CORS\n\napp = Flask(__name__)\nCORS(app)\n\n# Project: ${name}\n# Requirement: ${prompt}\n\n@app.route('/health')\ndef health():\n    return jsonify({"status": "healthy", "service": "${cleanName}"})\n\n@app.route('/api/data', methods=['GET'])\ndef get_data():\n    return jsonify({\n        "project": "${name}",\n        "description": "${prompt.replace(/"/g, '\\"')}",\n        "items": [\n            {"id": 1, "title": "Model Prediction Item", "confidence": 0.98},\n            {"id": 2, "title": "Diagnostic Report", "confidence": 0.94}\n        ]\n    })\n\nif __name__ == '__main__':\n    app.run(host='0.0.0.0', port=5000, debug=True)\n`,
        },
        {
          path: 'requirements.txt',
          content: `flask>=3.0.0\nflask-cors>=4.0.0\ngunicorn>=21.2.0\npytest>=8.0.0\n`,
        },
        {
          path: '.env.example',
          content: `PORT=5000\nFLASK_ENV=development\nSECRET_KEY=dev-secret-key\n`,
        },
        {
          path: 'README.md',
          content: `# ${name}\n\nGenerated by NEXORA AI.\n\n### Requirement\n${prompt}\n\n### Run Instructions\n\`\`\`bash\npip install -r requirements.txt\npython app.py\n\`\`\`\n`,
        },
      ];

    case 'node':
      return [
        {
          path: 'package.json',
          content: JSON.stringify(
            {
              name: cleanName,
              version: '1.0.0',
              type: 'module',
              scripts: {
                start: 'node src/index.js',
                dev: 'node --watch src/index.js',
                test: 'node --test',
              },
              dependencies: {
                express: '^4.21.2',
                cors: '^2.8.5',
                dotenv: '^16.4.7',
              },
            },
            null,
            2
          ),
        },
        {
          path: 'src/index.js',
          content: `import express from 'express';\nimport cors from 'cors';\nimport dotenv from 'dotenv';\n\ndotenv.config();\nconst app = express();\nconst PORT = process.env.PORT || 3000;\n\napp.use(cors());\napp.use(express.json());\n\n// Project: ${name}\n// Requirement: ${prompt}\n\napp.get('/health', (_req, res) => {\n  res.json({ status: 'healthy', project: '${name}' });\n});\n\napp.get('/api/items', (_req, res) => {\n  res.json([\n    { id: '1', title: 'Healthcare Diagnostic Record', verified: true },\n    { id: '2', title: 'Autonomous Patient Telemetry', verified: true }\n  ]);\n});\n\napp.listen(PORT, () => {\n  console.log(\`${name} backend listening on port \${PORT}\`);\n});\n`,
        },
        {
          path: '.env.example',
          content: `PORT=3000\nNODE_ENV=development\n`,
        },
        {
          path: 'README.md',
          content: `# ${name}\n\nGenerated by NEXORA AI.\n\n### Requirements\n${prompt}\n\n### Run Instructions\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`,
        },
      ];

    case 'react':
    default:
      return [
        {
          path: 'package.json',
          content: JSON.stringify(
            {
              name: cleanName,
              version: '0.1.0',
              private: true,
              type: 'module',
              scripts: {
                dev: 'vite',
                build: 'vite build',
              },
              dependencies: {
                react: '^18.3.1',
                'react-dom': '^18.3.1',
                'lucide-react': '^0.475.0',
              },
              devDependencies: {
                '@vitejs/plugin-react': '^4.3.4',
                vite: '^6.1.0',
              },
            },
            null,
            2
          ),
        },
        {
          path: 'index.html',
          content: `<!DOCTYPE html>\n<html lang="en">\n  <head>\n    <meta charset="UTF-8" />\n    <title>${name}</title>\n    <meta name="viewport" content="width=device-width, initial-scale=1.0" />\n  </head>\n  <body>\n    <div id="root"></div>\n    <script type="module" src="/src/main.jsx"></script>\n  </body>\n</html>\n`,
        },
        {
          path: 'src/main.jsx',
          content: `import React from 'react';\nimport ReactDOM from 'react-dom/client';\nimport App from './App';\n\nReactDOM.createRoot(document.getElementById('root')).render(\n  <React.StrictMode>\n    <App />\n  </React.StrictMode>\n);\n`,
        },
        {
          path: 'src/App.jsx',
          content: `import React, { useState } from 'react';\n\nexport default function App() {\n  const [count, setCount] = useState(0);\n\n  return (\n    <div style={{ fontFamily: 'sans-serif', padding: '2rem', textAlign: 'center' }}>\n      <h1>${name}</h1>\n      <p style={{ color: '#666' }}>${prompt.replace(/"/g, '\\"')}</p>\n      <button onClick={() => setCount(c => c + 1)} style={{ padding: '0.5rem 1rem', cursor: 'pointer' }}>\n        Verified Interactions: {count}\n      </button>\n    </div>\n  );\n}\n`,
        },
        {
          path: 'README.md',
          content: `# ${name}\n\nGenerated by NEXORA AI Universal Platform.\n\n### Requirement Prompt\n${prompt}\n\n### Setup\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`,
        },
      ];
  }
}

